class Movie {
  final String id;
  final String title;
  final int year;
  final String ageRating;
  final String runtime;
  final String description;
  final String image;
  final String screeningDate;

  const Movie({
    required this.id,
    required this.title,
    required this.year,
    required this.ageRating,
    required this.runtime,
    required this.description,
    required this.image,
    required this.screeningDate,
  });
}